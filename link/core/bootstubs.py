#!/usr/bin/env python3
# Pocket Arcade link core: tiny stand-in boot ROMs. GPL-3.0-or-later (see ../../LICENSE).
#
# SameBoy needs a boot ROM. Nintendo's are not ours to ship, and SameBoy's own (MIT) need RGBDS to
# assemble, so these two stubs, written here, do only what a game relies on: they leave the
# registers and I/O as the real boot ROMs leave them and hand over at $0100. No logo, no sound.
# Writes bootstubs.h (C arrays) next to this file.
import os

def dmg():
    c = bytearray()
    c += bytes([0x31, 0xFE, 0xFF])             # ld sp,$FFFE
    c += bytes([0x3E, 0x80, 0xE0, 0x26])       # ld a,$80 / ldh [NR52],a   sound on
    c += bytes([0x3E, 0xF3, 0xE0, 0x25])       # ld a,$F3 / ldh [NR51],a
    c += bytes([0x3E, 0x77, 0xE0, 0x24])       # ld a,$77 / ldh [NR50],a
    c += bytes([0x3E, 0xFC, 0xE0, 0x47])       # ld a,$FC / ldh [BGP],a
    c += bytes([0x3E, 0x91, 0xE0, 0x40])       # ld a,$91 / ldh [LCDC],a  LCD on
    c += bytes([0x21, 0xB0, 0x01, 0xE5, 0xF1]) # ld hl,$01B0 / push hl / pop af   A=$01 F=$B0
    c += bytes([0x01, 0x13, 0x00])             # ld bc,$0013
    c += bytes([0x11, 0xD8, 0x00])             # ld de,$00D8
    c += bytes([0x21, 0x4D, 0x01])             # ld hl,$014D
    return finish(c, 0x100, 0x01)

def cgb():
    PAL = 0xF0                                 # four greys at $00F0-$00F7 (RGB555): white, light, dark, black
    pal = b''.join(v.to_bytes(2, 'little') for v in (0x7FFF, 0x5294, 0x294A, 0x0000))
    c = bytearray()
    c += bytes([0x31, 0xFE, 0xFF])             # ld sp,$FFFE
    c += bytes([0xFA, 0x43, 0x01])             # ld a,[$0143]   CGB flag of the cartridge
    c += bytes([0xE0, 0x4C])                   # ldh [KEY0],a   (bit 7 set: Color game)
    c += bytes([0xCB, 0x7F])                   # bit 7,a
    jr_at = len(c); c += bytes([0x20, 0x00])   # jr nz,.common  (patched below)
    # A Game Boy game on a Game Boy Color: compatibility mode and grey palettes
    c += bytes([0x3E, 0x04, 0xE0, 0x4C])       # ld a,$04 / ldh [KEY0],a
    c += bytes([0x3E, 0x01, 0xE0, 0x6C])       # ld a,$01 / ldh [OPRI],a
    for idx, dat in ((0x68, 0x69), (0x6A, 0x6B)):
        c += bytes([0x3E, 0x80, 0xE0, idx])    # ld a,$80 / ldh [BCPS or OCPS],a   auto-increment
        c += bytes([0x0E, 4])                  # ld c,4         four palettes of the same greys
        c += bytes([0x21, PAL, 0x00])          # .pal: ld hl,PAL
        c += bytes([0x06, 8])                  # ld b,8
        c += bytes([0x2A, 0xE0, dat])          # .byte: ld a,[hl+] / ldh [BCPD or OCPD],a
        c += bytes([0x05, 0x20, 0xFA])         # dec b / jr nz,.byte
        c += bytes([0x0D, 0x20, 0xF2])         # dec c / jr nz,.pal
    common = len(c)
    c[jr_at + 1] = (common - (jr_at + 2)) & 0xFF
    c += bytes([0x3E, 0x80, 0xE0, 0x26, 0x3E, 0xF3, 0xE0, 0x25, 0x3E, 0x77, 0xE0, 0x24])  # sound on
    c += bytes([0x3E, 0xFC, 0xE0, 0x47])       # BGP
    c += bytes([0x3E, 0x91, 0xE0, 0x40])       # LCD on
    c += bytes([0x21, 0x80, 0x11, 0xE5, 0xF1]) # A=$11 F=$80
    c += bytes([0x01, 0x00, 0x00, 0x11, 0x56, 0xFF, 0x21, 0x0D, 0x00])  # BC=$0000 DE=$FF56 HL=$000D
    c += bytes([0xC3, 0xFC, 0x00])             # jp $00FC
    assert len(c) <= PAL
    out = bytearray(finish(c, 0x900, 0x11))
    out[PAL:PAL + 8] = pal
    return bytes(out)

def finish(code, size, a_final):
    """Pad with nops, then `ld a,a_final / ldh [$FF50],a` at $00FC so the boot ROM unmaps at $0100."""
    assert len(code) <= 0xF0
    out = bytearray([0x00] * size)
    out[:len(code)] = code
    out[0xFC:0x100] = bytes([0x3E, a_final, 0xE0, 0x50])
    return bytes(out)

def carray(name, data):
    rows = [', '.join('0x%02X' % b for b in data[i:i+16]) for i in range(0, len(data), 16)]
    return 'static const unsigned char %s[%d] = {\n    %s\n};\n' % (name, len(data), ',\n    '.join(rows))

if __name__ == '__main__':
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, 'bootstubs.h'), 'w') as f:
        f.write('/* Generated by bootstubs.py; do not edit. */\n')
        f.write(carray('boot_dmg', dmg()))
        f.write(carray('boot_cgb', cgb()))
